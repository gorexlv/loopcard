class AppLocalizations {
  const AppLocalizations(this.localeKey);

  final String localeKey;

  static const supportedLocales = <Locale>[
    Locale('en'),
    Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hans'),
    Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hant'),
    Locale('ja'),
    Locale('ko'),
    Locale('es'),
    Locale('fr'),
    Locale('de'),
    Locale('pt'),
    Locale('ru'),
  ];

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations) ??
      const AppLocalizations('en');

  @visibleForTesting
  static Set<String> translationKeysFor(Locale locale) {
    final key = resolveLocaleKey(locale);
    return Set.unmodifiable({
      ...?_translations[key]?.keys,
      ...?_authTranslations[key]?.keys,
    });
  }

  String tr(String key, [Map<String, Object> values = const {}]) {
    var text =
        (_translations[localeKey] ?? _translations['en'])?[key] ??
        _authTranslations[localeKey]?[key] ??
        _translations['en']![key] ??
        _authTranslations['en']?[key] ??
        key;
    for (final entry in values.entries) {
      text = text.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return text;
  }

  String deckTitle(String id, String fallback) => switch (id) {
    'everyday-words' => tr('deckWordsTitle'),
    'chemistry-formulas' => tr('deckFormulaTitle'),
    _ => fallback,
  };

  String deckSubtitle(String id, String fallback) => switch (id) {
    'everyday-words' => tr('deckWordsSubtitle'),
    'chemistry-formulas' => tr('deckFormulaSubtitle'),
    _ => fallback,
  };

  String sectionTitle(String title) => switch (title) {
    '核心释义' => tr('sectionMeaning'),
    '例句搭配' => tr('sectionExamples'),
    '易错辨析' => tr('sectionDistinction'),
    '化学式' => tr('sectionFormula'),
    '组成' => tr('sectionComposition'),
    '要点' => tr('sectionKeyPoints'),
    _ => title,
  };

  String languageName(Locale? locale) {
    if (locale == null) return tr('systemDefault');
    final key = resolveLocaleKey(locale);
    return const {
          'en': 'English',
          'zh-Hans': '简体中文',
          'zh-Hant': '繁體中文',
          'ja': '日本語',
          'ko': '한국어',
          'es': 'Español',
          'fr': 'Français',
          'de': 'Deutsch',
          'pt': 'Português',
          'ru': 'Русский',
        }[key] ??
        locale.toLanguageTag();
  }

  static String resolveLocaleKey(Locale locale) {
    if (locale.languageCode == 'zh') {
      final traditional =
          locale.scriptCode == 'Hant' ||
          const {'TW', 'HK', 'MO'}.contains(locale.countryCode);
      return traditional ? 'zh-Hant' : 'zh-Hans';
    }
    return _translations.containsKey(locale.languageCode)
        ? locale.languageCode
        : 'en';
  }

  static Locale resolvePreferredLocale(List<Locale>? preferredLocales) {
    for (final preferred in preferredLocales ?? const <Locale>[]) {
      final key = resolveLocaleKey(preferred);
      for (final supported in supportedLocales) {
        if (resolveLocaleKey(supported) == key) return supported;
      }
    }
    return const Locale('en');
  }
}

extension AppLocalizationsX on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
}

